export function getScenarioResponse(controllable: string, trigger: string): string | null {
  const scenarios = COMMON_SCENARIOS[controllable as keyof typeof COMMON_SCENARIOS] || [];
  const match = scenarios.find(s => 
    trigger.toLowerCase().includes(s.trigger.toLowerCase()) ||
    s.trigger.toLowerCase().includes(trigger.toLowerCase())
  );
  return match?.response || null;
}

